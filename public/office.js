  // カタパルト発進(#46)。
  //
  // 「勢い」は **速度カーブ + 残像 + カタパルト側の演出** の 3 つで出す。
  // キャラを傾けたり引き伸ばしたりはしない: それをやると character.js に手が
  // 要り、ボスの回帰(4 コマの画素一致)の基準を取り直すことになる。
  // ここに書いたものはすべて office.js に閉じている。
  //
  // 速度は **初速 = 歩行の boost 倍から指数で歩行速度へ落とす**。
  // 入口(72, 505)からデスク(480, 350)までの 436px は、等速 170px/s では
  // 2.57 秒かかっていたが、この曲線では 1.2 秒で着く(伸びる距離は
  // (boost - 1) × WALK_SPEED × tau = 250px ぶん)
  const LAUNCH = {
    boost: 4.5,   // 初速の倍率(765px/s から始まる)
    tau: 0.42,    // 減速の時定数(秒)
    flash: 0.34,  // ハッチのフラッシュが消えるまでの秒数
    lampSec: 0.9, // 警告灯が明滅している秒数
  };

  // ハッチの発進演出。age は最後の発進からの経過秒(まだ一度も発進していなければ
  // Infinity)。**床の誘導灯は #50 で廃止した** — 置いてあった発進デッキの鉄板ごと
  // 省いたためで、床に直接ランプだけを残すと足元の装飾が増えて読みづらくなる
  function drawDeck(g, age) {
    g.clear();
    // ハッチの上の警告灯。発進のあいだだけ赤く明滅する
    const lamp = age < LAUNCH.lampSec;
    g.beginFill(lamp ? 0xe8544a : 0x4d545e, lamp ? 0.55 + 0.45 * Math.abs(Math.sin(age * 18)) : 0.8)
      .drawRoundedRect(52, 379, 42, 8, 3)
      .endFill();
    // 発進口のフラッシュ。射出の瞬間に口が光り、広がりながら消える
    if (age < LAUNCH.flash) {
      const k = age / LAUNCH.flash;
      g.beginFill(0xfff3c4, 0.75 * (1 - k))
        .drawEllipse(108, 505, 12 + 52 * k, 28 + 34 * k)
        .endFill();
    }
  }

  // 充電の明滅(#47)。充電中(active)は光を強く脈打たせ、LED を下から順に灯して
  // 「充電が進んでいる」ことを見せる。誰も居ないときは待機の淡い光だけにする。
  // 球体側は一切いじらない(明滅もステーション側だけで出す)
  function drawCharge(g, at, time, active) {
    const cx = at.x;
    const cy = at.y;
    g.clear();
    // パッドの光。充電中は速く強く、待機中はゆっくり淡く
    const pulse = 0.5 - 0.5 * Math.cos(time * (active ? 2.4 : 0.9));
    g.beginFill(0x5fd8c8, active ? 0.22 + pulse * 0.4 : 0.10)
      .drawEllipse(cx, cy + 37, 32, 7)
      .endFill();
    // 給電ポストの LED(3 段)。充電中は 0→3 個を 0.5 秒ごとに繰り返す
    const lit = active ? Math.floor(time * 2) % 4 : 1;
    for (let i = 0; i < 3; i++) {
      const on = i < lit;
      g.beginFill(on ? 0x53d98a : 0x2b2f36, on ? 0.95 : 0.85)
        .drawRoundedRect(cx + 54, cy + 2 - i * 11, 8, 7, 2)
        .endFill();
    }
  }

